-- Tablas existentes (copia exacta de InsForge, solo estructura)
-- ============================================================
CREATE TABLE public."Polygons" (
  id integer generated by default as identity primary key,
  geom geometry,
  "MZA" INT2
);

CREATE TABLE public.actualizaciones_parcela (
  id integer generated by default as identity primary key,
  parcela_codigo character varying(50) not null,
  tipo character varying(80) not null,
  descripcion text not null,
  created_at timestamp with time zone not null default now()
);

CREATE TABLE public.calles (
  id integer generated by default as identity primary key,
  geom geometry,
  fid bigint,
  "Asfalto" character varying(250),
  tipo integer
);

CREATE TABLE public.encuestas (
  id integer generated by default as identity primary key,
  obra_prioritaria character varying(100) not null,
  sector character varying(120),
  lat double precision,
  lon double precision,
  geom geometry,
  created_at timestamp with time zone not null default now()
);

CREATE TABLE public.entradas (
  id integer generated by default as identity primary key,
  geom geometry,
  fid bigint,
  "Entradas_barrio" character varying
);

CREATE TABLE public.informacion (
  id integer generated by default as identity primary key,
  informacion text,
  ubicacion double precision,
  geom geometry
);

CREATE TABLE public.luminaria_publica (
  id integer generated by default as identity primary key,
  fid bigint,
  geom geometry
);

CREATE TABLE public.manzanas (
  id integer generated by default as identity primary key,
  codigo character varying(30) not null,
  nombre character varying(120),
  geom geometry not null,
  mza character varying(255)
);

CREATE TABLE public.parcelas (
  id integer generated by default as identity primary key,
  codigo character varying(50) not null,
  manzana_codigo character varying(30),
  superficie_m2 numeric,
  uso character varying(80) default 'Residencial'::character varying,
  agua boolean default false,
  cloacas boolean default false,
  electricidad boolean default true,
  pavimento boolean default false,
  alumbrado boolean default true,
  geom geometry not null
);

CREATE TABLE public.problemas (
  id integer generated by default as identity primary key,
  categoria character varying(80) not null,
  descripcion text not null,
  lat double precision,
  lon double precision,
  geom geometry,
  estado character varying(40) not null default 'Nuevo'::character varying,
  created_at timestamp with time zone not null default now()
);

CREATE TABLE public.propuestas (
  id integer generated by default as identity primary key,
  titulo character varying(180) not null,
  categoria character varying(80) not null,
  descripcion text not null,
  estado character varying(40) not null default 'Nueva'::character varying,
  lat double precision,
  lon double precision,
  geom geometry,
  created_at timestamp with time zone not null default now()
);

CREATE TABLE public.road (
  id integer generated by default as identity primary key,
  geom geometry,
  fid bigint,
  full_id character varying,
  osm_id character varying,
  osm_type character varying,
  highway character varying,
  name character varying,
  surface character varying,
  maxspeed character varying,
  ref character varying
);

CREATE TABLE public.solicitudes (
  id integer generated by default as identity primary key,
  tipo character varying(100) not null,
  descripcion text not null,
  lat double precision,
  lon double precision,
  geom geometry,
  estado character varying(40) not null default 'Nueva'::character varying,
  created_at timestamp with time zone not null default now()
);

CREATE TABLE public.waterways (
  id integer generated by default as identity primary key,
  geom geometry,
  fid bigint,
  full_id character varying,
  osm_id character varying,
  osm_type character varying,
  waterway character varying,
  name character varying
);

