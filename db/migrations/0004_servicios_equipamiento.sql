-- =============================================================================
--  0004_servicios_equipamiento.sql · Barrio Mama Antula
-- -----------------------------------------------------------------------------
--    equipamiento ... puntos y polígonos de servicios a la comunidad
--                     (educativo, salud, seguridad, deportivo, ...)
--    servicios ...... redes y puntos de infraestructura
--                     (agua, cloaca, gas, electricidad, residuos, ...)
--    luminarias ..... alumbrado público (capa `luminaria.gpkg` del QGIS)
--
--  Nota sobre `informacion`: la tabla heredada `informacion` (4 puntos: 3 de
--  policía y el Jardín Mama Antula) es equipamiento. Su traspaso está en
--  db/migrations/opcionales/0001_informacion_a_equipamiento.sql, para que esta
--  migración no cambie nada de lo que hoy ve el visor.
--
--  Idempotente. Ver docs/02-modelo-gis.md.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 1. Equipamiento
-- ---------------------------------------------------------------------------
create table if not exists public.equipamiento (
  id            integer generated by default as identity primary key,
  codigo        text unique,
  nombre        text not null,
  tipo          text not null,
  dominio_tipo  text generated always as ('tipo_equipamiento') stored,
  subtipo       text,
  direccion     text,
  telefono      text,
  horario       text,
  gestion       text not null default 'sin_dato',
  manzana_id    integer,
  barrio_id     integer,
  observaciones text,
  geom          geometry(Point, 4326) not null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint equipamiento_gestion_ck check (gestion in ('publico', 'privado', 'vecinal', 'mixto', 'sin_dato'))
);

create index if not exists equipamiento_geom_gix on public.equipamiento using gist (geom);
create index if not exists equipamiento_tipo_idx on public.equipamiento (tipo);

drop trigger if exists trg_equipamiento_updated_at on public.equipamiento;
create trigger trg_equipamiento_updated_at
  before update on public.equipamiento
  for each row execute function public.set_updated_at();

comment on table public.equipamiento is
  'Equipamiento comunitario. Reemplaza a la capa heredada `informacion`. '
  'Solo puntos: si un equipamiento ocupa una manzana entera, además se marca manzanas.tipo = equipamiento.';

-- ---------------------------------------------------------------------------
-- 2. Servicios urbanos
-- ---------------------------------------------------------------------------
create table if not exists public.servicios (
  id            integer generated by default as identity primary key,
  codigo        text,
  nombre        text,
  tipo          text not null,
  dominio_tipo  text generated always as ('tipo_servicio') stored,
  subtipo       text,
  estado        text not null default 'sin_dato',
  dominio_estado text generated always as ('estado_servicio') stored,
  prestador     text,
  descripcion   text,
  manzana_id    integer,
  barrio_id     integer,
  observaciones text,
  geom          geometry(Geometry, 4326) not null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint servicios_geom_tipo_ck check (
    st_geometrytype(geom) in
      ('ST_Point', 'ST_MultiPoint', 'ST_LineString', 'ST_MultiLineString', 'ST_Polygon', 'ST_MultiPolygon')
  ),
  constraint servicios_geom_no_vacia_ck check (not st_isempty(geom))
);

create index if not exists servicios_geom_gix on public.servicios using gist (geom);
create index if not exists servicios_tipo_idx on public.servicios (tipo);

drop trigger if exists trg_servicios_updated_at on public.servicios;
create trigger trg_servicios_updated_at
  before update on public.servicios
  for each row execute function public.set_updated_at();

comment on table public.servicios is
  'Redes y puntos de servicios. Es una tabla de geometría libre (punto, línea o polígono) '
  'porque una red de agua es línea, un contenedor es punto y una planta puede ser polígono. '
  'El campo subtipo distingue red / punto / instalación (valores libres, revisar en cada carga).';

-- ---------------------------------------------------------------------------
-- 3. Luminarias (alumbrado público)
-- ---------------------------------------------------------------------------
create table if not exists public.luminarias (
  id             integer generated by default as identity primary key,
  codigo         text,
  tipo           text not null default 'otro',
  dominio_tipo   text generated always as ('tipo_luminaria') stored,
  potencia_w     integer,
  altura_m       numeric(5,2),
  soporte        text,
  estado         text not null default 'sin_dato',
  dominio_estado text generated always as ('estado_luminaria') stored,
  calle_id       integer,
  manzana_id     integer,
  barrio_id      integer,
  observaciones  text,
  geom           geometry(Point, 4326) not null,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  constraint luminarias_soporte_ck check (
    soporte is null or soporte in ('poste_madera', 'poste_hormigon', 'columna', 'muro', 'otro')
  ),
  constraint luminarias_potencia_ck check (potencia_w is null or potencia_w between 1 and 2000),
  constraint luminarias_altura_ck   check (altura_m is null or altura_m between 1 and 30)
);

create index if not exists luminarias_geom_gix on public.luminarias using gist (geom);
create index if not exists luminarias_calle_idx on public.luminarias (calle_id);

drop trigger if exists trg_luminarias_updated_at on public.luminarias;
create trigger trg_luminarias_updated_at
  before update on public.luminarias
  for each row execute function public.set_updated_at();

comment on table public.luminarias is
  'Alumbrado público. Origen: luminaria.gpkg del proyecto QGIS. '
  'Se mantiene separada de `servicios` porque tiene atributos técnicos propios (potencia, altura, soporte).';

-- ---------------------------------------------------------------------------
-- 4. Claves foráneas
-- ---------------------------------------------------------------------------
do $do$
declare
  r        record;
  v_malos  bigint;
  v_nombre text;
begin
  -- 4.a Referencias entre capas --------------------------------------------
  for r in
    select * from (values
      ('equipamiento', 'manzana_id', 'manzanas', 'id'),
      ('equipamiento', 'barrio_id',  'barrios',  'id'),
      ('servicios',    'manzana_id', 'manzanas', 'id'),
      ('servicios',    'barrio_id',  'barrios',  'id'),
      ('luminarias',   'calle_id',   'calles',   'id'),
      ('luminarias',   'manzana_id', 'manzanas', 'id'),
      ('luminarias',   'barrio_id',  'barrios',  'id')
    ) as t(tabla, columna, ref_tabla, ref_columna)
  loop
    if not exists (
      select 1 from pg_constraint
       where conname = r.tabla || '_' || r.columna || '_fk'
         and conrelid = format('public.%I', r.tabla)::regclass
    ) then
      execute format(
        'alter table public.%I add constraint %I foreign key (%I) references public.%I (%I) not valid',
        r.tabla, r.tabla || '_' || r.columna || '_fk', r.columna, r.ref_tabla, r.ref_columna);
    end if;

    begin
      execute format('alter table public.%I validate constraint %I',
                     r.tabla, r.tabla || '_' || r.columna || '_fk');
    exception when foreign_key_violation then
      execute format(
        'select count(*) from public.%I x where x.%I is not null and not exists (select 1 from public.%I y where y.%I = x.%I)',
        r.tabla, r.columna, r.ref_tabla, r.ref_columna, r.columna) into v_malos;
      raise warning 'FK %.%: % fila(s) sin destino válido.', r.tabla, r.columna, v_malos;
    end;
  end loop;

  -- 4.b Referencias a catálogos --------------------------------------------
  for r in
    select * from (values
      ('equipamiento', 'tipo',   'tipo_equipamiento'),
      ('servicios',    'tipo',   'tipo_servicio'),
      ('servicios',    'estado', 'estado_servicio'),
      ('luminarias',   'tipo',   'tipo_luminaria'),
      ('luminarias',   'estado', 'estado_luminaria')
    ) as t(tabla, columna, dominio)
  loop
    v_nombre := r.tabla || '_' || r.columna || '_cat_fk';

    if not exists (
      select 1 from pg_constraint
       where conname = v_nombre and conrelid = format('public.%I', r.tabla)::regclass
    ) then
      execute format(
        'alter table public.%I add constraint %I foreign key (%I, %I) references public.catalogos (dominio, codigo) not valid',
        r.tabla, v_nombre, 'dominio_' || r.columna, r.columna);
    end if;

    begin
      execute format('alter table public.%I validate constraint %I', r.tabla, v_nombre);
    exception when foreign_key_violation then
      execute format(
        'select count(*) from public.%I x where x.%I is not null and not exists (select 1 from public.catalogos c where c.dominio = %L and c.codigo = x.%I)',
        r.tabla, r.columna, r.dominio, r.columna) into v_malos;
      raise warning 'Catálogo %: %.% tiene % fila(s) fuera del catálogo.', r.dominio, r.tabla, r.columna, v_malos;
    end;
  end loop;
end
$do$;
