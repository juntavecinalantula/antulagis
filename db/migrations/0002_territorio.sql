-- =============================================================================
--  0002_territorio.sql · Barrio Mama Antula · InsForge (PostgreSQL + PostGIS)
-- -----------------------------------------------------------------------------
--  Capas territoriales: el esqueleto del barrio.
--
--    barrios            (nueva)  · límite del barrio
--    manzanas           (existe) · 132 polígonos en InsForge
--    parcelas           (existe) · vacía
--    calles             (existe) · 70 líneas (tipo 1 = asfalto, 2 = ripio)
--    waterways          (existe) · 3 cauces (capa heredada de OSM)
--    entradas           (existe) · 9 líneas (Actual / Proyecto)
--    espacios_publicos  (nueva)  · plazas, canchas, verdes
--
--  Regla de esta migración: NO se renombra ni se borra nada de lo que ya existe
--  (el visor y el proyecto QGIS siguen funcionando tal cual). Solo se agregan
--  columnas, restricciones e índices, y se completan los datos derivados.
--
--  Idempotente. Ver docs/02-modelo-gis.md para el significado de cada campo.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 1. Límite del barrio
-- ---------------------------------------------------------------------------
create table if not exists public.barrios (
  id            integer generated by default as identity primary key,
  codigo        text not null unique,
  nombre        text not null,
  jurisdiccion  text,
  departamento  text,
  municipio     text,
  geom          geometry(MultiPolygon, 4326) not null,
  superficie_m2 double precision generated always as (st_area(st_transform(geom, 5346))) stored,
  observaciones text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint barrios_geom_valida   check (st_isvalid(geom)),
  constraint barrios_geom_no_vacia check (not st_isempty(geom))
);

create index if not exists barrios_geom_gix on public.barrios using gist (geom);

drop trigger if exists trg_barrios_updated_at on public.barrios;
create trigger trg_barrios_updated_at
  before update on public.barrios
  for each row execute function public.set_updated_at();

comment on table public.barrios is
  'Límite del barrio. Es la capa madre: todo lo demás se ubica dentro de este polígono. '
  'Se espera UNA fila para el barrio Mama Antula; el modelo admite varias.';

-- ---------------------------------------------------------------------------
-- 2. Manzanas (tabla existente: id, codigo, nombre, mza, geom)
-- ---------------------------------------------------------------------------
alter table public.manzanas add column if not exists barrio_id     integer;
alter table public.manzanas add column if not exists tipo          text;
alter table public.manzanas add column if not exists dominio_tipo  text generated always as ('tipo_manzana') stored;
alter table public.manzanas add column if not exists observaciones text;
alter table public.manzanas add column if not exists created_at    timestamptz not null default now();
alter table public.manzanas add column if not exists updated_at    timestamptz not null default now();
alter table public.manzanas add column if not exists superficie_m2 double precision
  generated always as (st_area(st_transform(geom, 5346))) stored;
alter table public.manzanas add column if not exists perimetro_m double precision
  generated always as (st_perimeter(st_transform(geom, 5346))) stored;

-- Clasificación a partir de los datos que ya están cargados: las manzanas cuyo
-- código o nombre dice "baldio" son baldíos; el resto, manzanas urbanizadas.
update public.manzanas
   set tipo = case
                when lower(coalesce(codigo, '') || ' ' || coalesce(nombre, '')) like '%baldio%'
                  then 'baldio'
                else 'manzana'
              end
 where tipo is null;

alter table public.manzanas alter column tipo set default 'manzana';
alter table public.manzanas alter column tipo set not null;

create index if not exists manzanas_geom_gix    on public.manzanas using gist (geom);
create index if not exists manzanas_barrio_idx  on public.manzanas (barrio_id);
create unique index if not exists manzanas_codigo_uk on public.manzanas (codigo) where codigo is not null;

drop trigger if exists trg_manzanas_updated_at on public.manzanas;
create trigger trg_manzanas_updated_at
  before update on public.manzanas
  for each row execute function public.set_updated_at();

comment on column public.manzanas.mza is
  'Número de manzana según el archivo original (1..138). No es único ni tiene el mismo criterio que codigo: revisar antes de usarlo como identificador.';
comment on column public.manzanas.codigo is
  'Código original de la digitalización. Convive con tres formatos: M-0NN, NNN y "Baldio NN". Ver docs/01-estado-actual.md.';

