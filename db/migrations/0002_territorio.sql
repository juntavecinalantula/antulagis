-- Completar desde la columna heredada `name` (3 filas: canal principal, sec 1, sec 3)
update public.waterways
   set nombre = name
 where nombre is null and name is not null;

update public.waterways
   set tipo = case
                when lower(coalesce(nombre, '')) like '%principal%' then 'canal_principal'
                when lower(coalesce(nombre, '')) like '%sec%'       then 'canal_secundario'
                when lower(coalesce(name,  '')) like '%principal%' then 'canal_principal'
                when lower(coalesce(name,  '')) like '%sec%'       then 'canal_secundario'
                else 'otro'
              end
 where tipo is null;

alter table public.waterways alter column tipo set not null;

create index if not exists waterways_geom_gix on public.waterways using gist (geom);

