alter table public.luminaria_publica add column if not exists estado        text not null default 'sin_dato';
alter table public.luminaria_publica add column if not exists dominio_estado text generated always as ('estado_luminaria') stored;
alter table public.luminaria_publica add column if not exists calle_id      integer;
alter table public.luminaria_publica add column if not exists manzana_id    integer;
alter table public.luminaria_publica add column if not exists barrio_id     integer;
