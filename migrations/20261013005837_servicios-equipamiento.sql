--    servicios .......... (NUEVA) redes y puntos de infraestructura
--    luminaria_publica .. (existe, 79 filas) se le agregan los atributos técnicos
--
--  IMPORTANTE: NO se crea una tabla `luminarias`. La capa ya existe en el
--  proyecto como `luminaria_publica` (79 puntos, con solo `fid`). Crear otra
--  habría duplicado la verdad; se extiende la existente.
--
--  Relación con `parcelas`: los booleanos agua/cloacas/electricidad/pavimento/
--  alumbrado de `parcelas` responden «¿esta parcela tiene el servicio?».
--  `servicios` responde «¿por dónde pasa la red?». Son cosas distintas y se
--  complementan; ver docs/02-modelo-gis.md.
--
--  Idempotente.
