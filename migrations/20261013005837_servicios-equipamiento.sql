-- ---------------------------------------------------------------------------
-- 1. Equipamiento
-- ---------------------------------------------------------------------------
create table if not exists public.equipamiento (
  id            integer generated by default as identity primary key,
  codigo        text unique,
  nombre        text not null,
  tipo          text not null,
  dominio_tipo  text generated always as ('tipo_equipamiento') stored,
  subtipo       text,
  direccion     text,
  telefono      text,
  horario       text,
  gestion       text not null default 'sin_dato',
  manzana_id    integer,
  barrio_id     integer,
  observaciones text,
  geom          geometry(Point, 4326) not null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint equipamiento_gestion_ck check (gestion in ('publico', 'privado', 'vecinal', 'mixto', 'sin_dato'))
);

create index if not exists equipamiento_geom_gix on public.equipamiento using gist (geom);
create index if not exists equipamiento_tipo_idx on public.equipamiento (tipo);

drop trigger if exists trg_equipamiento_updated_at on public.equipamiento;
create trigger trg_equipamiento_updated_at
  before update on public.equipamiento
  for each row execute function public.set_updated_at();

comment on table public.equipamiento is
  'Equipamiento comunitario (escuela, sala de salud, destacamento, capilla, club, salón vecinal...). '
  'Reemplaza a la capa heredada `informacion` (4 puntos: 3 de policía y el Jardín Mama Antula). '
  'Su traspaso está en docs/opcionales, para no cambiar lo que hoy ve el visor.';

-- ---------------------------------------------------------------------------
-- 2. Servicios urbanos
-- ---------------------------------------------------------------------------
create table if not exists public.servicios (
  id             integer generated by default as identity primary key,
  codigo         text,
  nombre         text,
  tipo           text not null,
  dominio_tipo   text generated always as ('tipo_servicio') stored,
  subtipo        text,
  estado         text not null default 'sin_dato',
  dominio_estado text generated always as ('estado_servicio') stored,
  prestador      text,
  descripcion    text,
  manzana_id     integer,
  barrio_id      integer,
  observaciones  text,
  geom           geometry(Geometry, 4326) not null,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  constraint servicios_geom_tipo_ck check (
    st_geometrytype(geom) in
      ('ST_Point', 'ST_MultiPoint', 'ST_LineString', 'ST_MultiLineString', 'ST_Polygon', 'ST_MultiPolygon')
  ),
  constraint servicios_geom_no_vacia_ck check (not st_isempty(geom))
);

create index if not exists servicios_geom_gix on public.servicios using gist (geom);
create index if not exists servicios_tipo_idx on public.servicios (tipo);

drop trigger if exists trg_servicios_updated_at on public.servicios;
create trigger trg_servicios_updated_at
  before update on public.servicios
  for each row execute function public.set_updated_at();

comment on table public.servicios is
  'Redes y puntos de servicios. Geometría libre (punto, línea o polígono) porque una red de agua '
  'es línea, un contenedor es punto y una planta puede ser polígono. '
  '`subtipo` distingue red / punto / instalación (texto libre: revisar en cada carga). '
  'El estado del servicio por parcela vive en parcelas.agua / cloacas / electricidad / pavimento / alumbrado.';

-- ---------------------------------------------------------------------------
-- 3. Luminarias: se EXTIENDE la capa existente `luminaria_publica`
