create index if not exists luminaria_publica_calle_idx on public.luminaria_publica (calle_id);

-- Restricciones: se agregan NOT VALID y se validan con aviso, para no abortar
-- la migración por datos viejos.
do $do$
declare
  r       record;
  v_malos bigint;
begin
  for r in
    select * from (values
      ('luminaria_publica_soporte_ck',  'soporte is null or soporte in (''poste_madera'', ''poste_hormigon'', ''columna'', ''muro'', ''otro'')'),
      ('luminaria_publica_potencia_ck', 'potencia_w is null or potencia_w between 1 and 2000'),
      ('luminaria_publica_altura_ck',   'altura_m is null or altura_m between 1 and 30')
    ) as t(nombre, condicion)
  loop
    if not exists (
      select 1 from pg_constraint
       where conname = r.nombre and conrelid = 'public.luminaria_publica'::regclass
    ) then
      execute format('alter table public.luminaria_publica add constraint %I check (%s) not valid',
                     r.nombre, r.condicion);
    end if;

    begin
      execute format('alter table public.luminaria_publica validate constraint %I', r.nombre);
    exception when check_violation then
      execute format('select count(*) from public.luminaria_publica x where not (coalesce(%s, true))',
                     r.condicion) into v_malos;
      raise warning 'Restricción % sobre luminaria_publica: % fila(s) no la cumplen.', r.nombre, v_malos;
    end;
  end loop;
end
$do$;

