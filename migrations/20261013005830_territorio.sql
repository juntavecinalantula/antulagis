-- ---------------------------------------------------------------------------
-- 9. Claves foráneas entre capas
--    Se crean NOT VALID para no fallar si quedaran filas viejas mal referenciadas;
--    después se intenta validar y, si no se puede, se avisa por consola con la
--    cantidad de filas a revisar. Nunca se borra ni se modifica un dato.
-- ---------------------------------------------------------------------------
do $do$
declare
  r       record;
  v_malos bigint;
begin
  for r in
    select * from (values
      ('manzanas',          'barrio_id',  'barrios',  'id'),
      ('parcelas',          'manzana_id', 'manzanas', 'id'),
      ('entradas',          'calle_id',   'calles',   'id'),
      ('espacios_publicos', 'manzana_id', 'manzanas', 'id'),
      ('espacios_publicos', 'barrio_id',  'barrios',  'id')
    ) as t(tabla, columna, ref_tabla, ref_columna)
  loop
    if not exists (
      select 1 from pg_constraint
       where conname = r.tabla || '_' || r.columna || '_fk'
         and conrelid = format('public.%I', r.tabla)::regclass
    ) then
      execute format(
        'alter table public.%I add constraint %I foreign key (%I) references public.%I (%I) not valid',
        r.tabla, r.tabla || '_' || r.columna || '_fk', r.columna, r.ref_tabla, r.ref_columna);
    end if;

    begin
      execute format('alter table public.%I validate constraint %I',
                     r.tabla, r.tabla || '_' || r.columna || '_fk');
    exception when foreign_key_violation then
      execute format(
        'select count(*) from public.%I x where x.%I is not null and not exists (select 1 from public.%I y where y.%I = x.%I)',
        r.tabla, r.columna, r.ref_tabla, r.ref_columna, r.columna) into v_malos;
      raise warning 'FK %.%: % fila(s) apuntan a un %.% inexistente. Corregir y volver a ejecutar ALTER TABLE ... VALIDATE CONSTRAINT.',
        r.tabla, r.columna, v_malos, r.ref_tabla, r.ref_columna;
    end;
  end loop;
end
$do$;

-- ---------------------------------------------------------------------------
-- 10. Claves foráneas a catálogos
--     Patrón: columna generada `dominio_<campo>` + FK compuesta (dominio, codigo).
-- ---------------------------------------------------------------------------
do $do$
declare
  r        record;
  v_malos  bigint;
  v_nombre text;
begin
  for r in
    select * from (values
      ('manzanas',          'tipo',     'tipo_manzana'),
      ('parcelas',          'uso',      'uso_parcela'),
      ('calles',            'material', 'material_calle'),
      ('calles',            'jerarquia','jerarquia_calle'),
      ('calles',            'sentido',  'sentido_calle'),
      ('calles',            'estado',   'estado_conservacion'),
      ('waterways',         'tipo',     'tipo_cauce'),
      ('waterways',         'estado',   'estado_cauce'),
      ('entradas',          'tipo',     'tipo_entrada'),
      ('entradas',          'estado',   'estado_entrada'),
      ('espacios_publicos', 'tipo',     'tipo_espacio_publico'),
      ('espacios_publicos', 'estado',   'estado_conservacion')
    ) as t(tabla, columna, dominio)
  loop
    v_nombre := r.tabla || '_' || r.columna || '_cat_fk';

    if not exists (
      select 1 from pg_constraint
       where conname = v_nombre and conrelid = format('public.%I', r.tabla)::regclass
    ) then
      execute format(
        'alter table public.%I add constraint %I foreign key (%I, %I) references public.catalogos (dominio, codigo) not valid',
        r.tabla, v_nombre, 'dominio_' || r.columna, r.columna);
    end if;

    begin
      execute format('alter table public.%I validate constraint %I', r.tabla, v_nombre);
    exception when foreign_key_violation then
      execute format(
        'select count(*) from public.%I x where x.%I is not null and not exists (select 1 from public.catalogos c where c.dominio = %L and c.codigo = x.%I)',
        r.tabla, r.columna, r.dominio, r.columna) into v_malos;
      raise warning 'Catálogo %: %.% tiene % fila(s) con valores fuera del catálogo. Agregar el valor a public.catalogos o corregir los datos, y volver a validar.',
        r.dominio, r.tabla, r.columna, v_malos;
    end;
  end loop;
end
$do$;

-- ---------------------------------------------------------------------------
-- 11. Restricciones de geometría y de código
--     Se agregan como NOT VALID y se validan con aviso: si alguna de las 132
--     manzanas actuales tuviera un anillo abierto, se avisa en lugar de abortar.
-- ---------------------------------------------------------------------------
do $do$
declare
  r       record;
  v_malos bigint;
begin
  for r in
    select * from (values
      ('manzanas',  'manzanas_geom_valida_ck',   'st_isvalid(geom)'),
      ('parcelas',  'parcelas_geom_valida_ck',   'st_isvalid(geom)'),
      ('calles',    'calles_geom_valida_ck',     'st_isvalid(geom)'),
      ('waterways', 'waterways_geom_valida_ck',  'st_isvalid(geom)'),
      ('entradas',  'entradas_geom_valida_ck',   'st_isvalid(geom)'),
      ('calles',    'calles_tipo_ck',            'tipo is null or tipo in (1, 2, 3, 4)')
    ) as t(tabla, nombre, condicion)
  loop
    if not exists (
      select 1 from pg_constraint
       where conname = r.nombre and conrelid = format('public.%I', r.tabla)::regclass
    ) then
      execute format('alter table public.%I add constraint %I check (%s) not valid',
                     r.tabla, r.nombre, r.condicion);
    end if;

    begin
      execute format('alter table public.%I validate constraint %I', r.tabla, r.nombre);
    exception when check_violation then
      execute format('select count(*) from public.%I x where not (coalesce(%s, true))',
                     r.tabla, r.condicion) into v_malos;
      raise warning 'Restricción % sobre public.%: % fila(s) no la cumplen. Corregir los datos y volver a validar.',
        r.nombre, r.tabla, v_malos;
    end;
  end loop;
end
$do$;

-- Unicidad de manzanas.codigo, solo si los datos actuales ya son únicos.
do $do$
declare
  v_dups integer;
begin
  if not exists (select 1 from pg_indexes where schemaname = 'public' and indexname = 'manzanas_codigo_uk') then
    select count(*) into v_dups
      from (select codigo from public.manzanas group by codigo having count(*) > 1) d;

    if v_dups = 0 then
      execute 'create unique index manzanas_codigo_uk on public.manzanas (codigo)';
    else
      raise warning 'No se creó el índice único manzanas_codigo_uk: hay % código(s) repetido(s).', v_dups;
    end if;
  end if;
end
$do$;
