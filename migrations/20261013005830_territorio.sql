create or replace function public.calcular_superficie_parcela()
returns trigger
language plpgsql
as $fn$
begin
  if new.geom is not null
     and (tg_op = 'INSERT' or new.geom is distinct from old.geom or new.superficie_m2 is null)
  then
    new.superficie_m2 := round(st_area(new.geom::geography)::numeric, 2);
  end if;
  return new;
end
$fn$;

comment on function public.calcular_superficie_parcela() is
  'Recalcula parcelas.superficie_m2 (numeric, preexistente) a partir de la geometría.';

